local H=require('speculation.relay.computation.formed_computation.common')
local ok,eq,count=H.counter()
local target=H.package('take',{H.value_context('done',{authority_inputs=1,authority_outputs=0})})
local tr=target:root('take')
local form=H.C.form_package(tr,1,'form')
local performer=H.C.perform_package({authority={inputs=1,outputs=0},values={inputs=0,outputs=1}},nil,'run')
local linked=H.link({target,form,performer})
local k,result=H.C.perform(linked,form:root('form'),performer:root('run'))
eq(k,'Hit')
eq(#result:alternative(1).authority.inputs,1,'capture source did not remain public ingress')
local exact=H.C.instantiate_form_capture(linked,form:root('form'))
local target_template=assert(H.Context.plug(target:definition(tr).family.items[1],{}))
ok(H.C.exact_double_perform_rejected(exact,target_template),
  'one exact capture fed two performances')
print('PASS tf 08: one-shotness follows exact capture scarcity, not an operation type ('..count()..')')
