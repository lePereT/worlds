local H=require('speculation.relay.computation.formed_computation.common')
local ok,eq,count=H.counter()
local target=H.package('target',{H.value_context('done')})
local tr=target:root('target')
local form=H.C.form_package(tr,0,'form')
local performer=H.C.perform_package({authority={inputs=0,outputs=0},values={inputs=0,outputs=1}},nil,'run')
local linked=H.link({target,form,performer})
local k,result=H.C.perform(linked,form:root('form'),performer:root('run'))
eq(k,'Hit')
local dk,direct=H.C.direct(linked,tr)
eq(dk,'Hit')
eq(H.faces(result),H.faces(direct),'root knowledge created a causal Face')
eq(H.Canonical.encode(result:alternative(1).geometry),H.Canonical.encode(direct:alternative(1).geometry),
  'root knowledge changed target Geometry')
print('PASS tf 07: semantic-root knowledge selects Geometry without becoming causality ('..count()..')')
