local H=require('speculation.relay.computation.formed_computation.common')
local ok,eq,count=H.counter()
local target=H.package('target',{H.value_context('done')})
local tr=target:root('target')
local form=H.C.form_package(tr,0,'form')
local perf=H.C.perform_package({authority={inputs=0,outputs=0},values={inputs=0,outputs=1}},nil,'run')
local linked=H.link({target,form,perf})
local kind,result=H.C.perform(linked,form:root('form'),perf:root('run'))
eq(kind,'Hit')
local dk,direct=H.C.direct(linked,tr)
eq(dk,'Hit')
eq(H.Canonical.encode(result:alternative(1)),H.Canonical.encode(direct:alternative(1)),
  'form/perform changed finite target meaning')
eq(H.output_value(result),'done')
ok(true)
print('PASS tf 03: finite form then perform collapses to direct Development meaning ('..count()..')')
