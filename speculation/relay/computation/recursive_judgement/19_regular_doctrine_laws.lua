local H=require('speculation.relay.computation.recursive_judgement.common')
 local K=H.K
 local ok,eq,count=H.counter()
local xy=H.bool_context({'x','y'})
 local rel=K.relation(xy,function(v) return v.x==v.y end)
local pub=K.point_value(H.bool_context({'x'}),'x',true)
local lifted=K.rename(pub,{x='x'},xy)
local left=K.exists(K.meet(rel,lifted),{'x'})
local right=K.meet(K.exists(rel,{'x'}),pub)
ok(K.equal(left,right),'Frobenius reciprocity failed')
local uv=H.bool_context({'u','v'})
 local renamed=K.rename(rel,{x='u',y='v'},uv)
local bc_left=K.exists(renamed,{'u'})
 local ex=K.exists(rel,{'x'})
 local bc_right=K.rename(ex,{x='u'},H.bool_context({'u'}))
ok(K.equal(bc_left,bc_right),'hiding/reindex stability failed')
print('PASS rj 19: restrictive knowledge obeys regular-doctrine hiding/substitution laws ('..count()..')')
