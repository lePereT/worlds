local H=require('speculation.relay.computation.recursive_judgement.common')
 local ok,eq,count=H.counter()
local p=H.rec_package('f',{H.base_bool_context(nil),H.unary_bool_context({definition='f'})},{{1,2}})
 local r=p:root('f')
 local a=H.Analysis.compute(p)
for depth=1,3 do local f=H.Search.family(p,r,depth)
 local s,row=H.Judgement.first_stable(p,r,H.state_bool(false),f,a)
 eq(s,'Hit','grounded preferred base did not stabilise')
 ok(row~=nil) end
print('PASS rj 12: grounded preferred alternative is stable independently of unfolding depth ('..count()..')')
