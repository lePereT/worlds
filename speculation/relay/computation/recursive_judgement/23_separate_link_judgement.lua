local H=require('speculation.relay.computation.recursive_judgement.common')
 local ok,eq,count=H.counter()
local g=H.rec_package('g',{H.base_bool_context(false)},{})
 local groot=g:root('g')
local f=H.RP.new({definitions={{identity='f',alternatives={H.unary_bool_context({root=groot}),H.base_bool_context(nil)},prefers={{1,2}}}}})
 local froot=f:root('f')
local linked=H.RP.link({f,g})
 local a=H.Analysis.compute(linked)
 local found=H.Search.family(linked,froot,2)
-- On true, g(false) cannot complete, so the fallback in separately compiled f is stable.
eq(H.Judgement.first_stable(linked,froot,H.state_bool(true),found,a),'Hit','separate semantic-root link changed priority reasoning')
local linked2=H.RP.link({H.roundtrip(f),H.roundtrip(g)})
 local a2=H.Analysis.compute(linked2)
 local found2=H.Search.family(linked2,froot,2)
eq(H.Judgement.first_stable(linked2,froot,H.state_bool(true),found2,a2),'Hit','roundtripped separate link changed Judgement')
print('PASS rj 23: separately compiled recursive roots retain stable Judgement semantics ('..count()..')')
