local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
local s,r=H.Channel.send('numbers',41),H.Channel.recv('numbers')
local each=H.C.each({s,r})
local ea=each:alternative(1)
eq(#ea.geometry.faces,2,'each changed sibling faces')
eq(#ea.authority.inputs,2,'each supplied sibling authority inputs')
eq(#ea.authority.outputs,4,'each consumed sibling authority outputs')
local together=H.C.together({s,r})
eq(#together:family().items,1,'matching rendezvous was ambiguous or absent')
local ta=together:alternative(1)
eq(#ta.geometry.faces,1,'rendezvous did not SCC-normalise to one joint Face')
eq(#ta.authority.inputs,0,'rendezvous left handshake ingress open')
eq(#ta.authority.outputs,2,'rendezvous did not leave exactly the two continuation outputs')
ok(true)
print('PASS cc 01: each preserves independent siblings; together closes their rendezvous ('..count()..')')
