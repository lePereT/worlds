local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
local C,L=H.C,H.Latch
local incomplete=C.together({L.seed('boot',3),L.count_down('boot'),L.count_down('boot'),L.await('boot',3)})
eq(#incomplete:family().items,0,'latch certified completion without all three arrivals')
local complete=C.together({L.seed('boot',3),L.count_down('boot'),L.count_down('boot'),L.count_down('boot'),L.await('boot',3)})
ok(#complete:family().items>=1,'three arrivals did not complete three-count latch')
local a=complete:alternative(1)
eq(#a.authority.inputs,0,'closed latch retained external authority input')
ok(#a.authority.outputs>=1,'completed latch lost continuation')
local wrong=C.together({L.seed('boot',1),L.count_down('other'),L.await('boot',1)})
eq(#wrong:family().items,0,'latch identity failed to reject foreign countdown')
ok(H.no_runtime_words(complete:bytes()))
print('PASS cc 44: latch completion is positive ownership of all arrived tokens, not observed absence ('..count()..')')
