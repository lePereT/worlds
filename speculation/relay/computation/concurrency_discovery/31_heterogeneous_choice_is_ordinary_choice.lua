local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
local select=H.C.choice(H.Channel.recv('wire'),H.Cell.take('box'))
eq(#select:family().items,2,'heterogeneous choice did not retain both ordinary alternatives')
local channel=H.C.together({select,H.Channel.send('wire',5)})
eq(#channel:family().items,1,'channel environment did not select channel alternative')
eq(H.value(channel,1,1),5,'channel-selected heterogeneous choice returned wrong value')
local cell=H.C.together({select,H.Cell.full('box',8)})
eq(#cell:family().items,1,'cell environment did not select cell alternative')
eq(H.value(cell,1,1),8,'cell-selected heterogeneous choice returned wrong value')
ok(H.no_runtime_words(channel:bytes()) and H.no_runtime_words(cell:bytes()))
print('PASS cc 31: heterogeneous channel/cell select is ordinary choice ('..count()..')')
