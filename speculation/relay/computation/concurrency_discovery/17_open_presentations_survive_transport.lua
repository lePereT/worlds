local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
local Package=H.C.Package()
local s=H.Channel.send('wire',17)
local r=H.Channel.recv('wire')
local transported_s=Package.decode(s:bytes())
local transported_r=Package.decode(r:bytes())
local direct=H.C.together({s,r})
local transported=H.C.together({transported_s,transported_r})
eq(direct:root(),transported:root(),'open Strand-supported interface changed across Package transport')
eq(direct:bytes(),transported:bytes(),'transported rendezvous changed canonical meaning')
eq(H.value(transported,1,1),17)
ok(true)
print('PASS cc 17: generic open Strand-supported interfaces survive separate transport unchanged ('..count()..')')
