local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
local p=H.C.together({H.Cell.empty('box'),H.Cell.put('box',41),H.Cell.take('box')})
eq(#p:family().items,1,'empty -> put -> take did not establish as one protocol network')
eq(H.value(p,1,1),41,'take did not receive the value stored by put')
local a=p:alternative(1)
eq(#a.geometry.faces,3,'cell protocol did not retain its three causal actions')
ok(H.G.face_reaches(a.geometry,1,2),'cell creation did not precede put')
ok(H.G.face_reaches(a.geometry,2,3),'put did not precede take')
ok(not p:bytes():find('cell_state',1,true),'cell acquired a runtime state-machine object')
print('PASS cc 25: a mutable cell is an ordinary open state protocol ('..count()..')')
