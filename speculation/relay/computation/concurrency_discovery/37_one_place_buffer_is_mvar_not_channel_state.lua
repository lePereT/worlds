local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
eq(H.Buffered.empty,H.MVar.empty,'buffer introduced a distinct empty-state implementation')
eq(H.Buffered.send,H.MVar.put,'buffer send is not MVar put')
eq(H.Buffered.recv,H.MVar.take,'buffer receive is not MVar take')
local state=H.Buffered.empty('buffer')
local full=H.Buffered.step(state,H.Buffered.send('buffer',17))
eq(#full:family().items,1,'buffered send incorrectly required simultaneous receiver')
eq(H.value(full,1,1),'full')
eq(H.value(full,1,2),17)
eq(#H.Buffered.step(full,H.Buffered.send('buffer',18)):family().items,0,
  'one-place buffer accepted a second send while full')
local empty=H.Buffered.step(full,H.Buffered.recv('buffer'))
eq(H.value(empty,1,1),'empty')
eq(H.value(empty,1,3),17,'buffer receive lost stored payload')
local next=H.Buffered.step(empty,H.Buffered.send('buffer',18))
eq(H.value(next,1,2),18,'buffer did not accept send after receive')
ok(H.no_runtime_words(next:bytes()))
print('PASS cc 37: one-place buffered channel is exactly the grounded MVar protocol ('..count()..')')
