local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
local network=H.C.together({H.Channel.send('known',123),H.Channel.recv('known')})
local p=H.finish(network,'complete')
eq(#p:family().items,1)
eq(#p:alternative(1).authority.inputs,0)
eq(#p:alternative(1).authority.outputs,0)
eq(H.value(p,1,1),'complete')
ok(H.no_runtime_words(p:bytes()))
ok(not p:bytes():find('known',1,true),'fully hidden channel identity survived closed computation')
print('PASS cc 12: fully known concurrency residualises no scheduler or channel runtime ('..count()..')')
