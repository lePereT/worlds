local H=require('speculation.relay.computation.concurrency_discovery.common')
local ok,eq,count=H.counter()
local actions={H.Channel.send('a',1),H.Channel.recv('a'),H.Channel.send('b',2),H.Channel.recv('b')}
local whole=H.Discovery.whole(actions)
local staged=H.Discovery.pairs(actions,{{1,2},{3,4}})
local reversed=H.Discovery.pairs(actions,{{3,4},{1,2}})
eq(#whole:alternative(1).geometry.faces,2,'independent rendezvous were serialised')
ok(not H.G.face_reaches(whole:alternative(1).geometry,1,2),'independent rendezvous gained causal order')
ok(not H.G.face_reaches(whole:alternative(1).geometry,2,1),'independent rendezvous gained reverse causal order')
local wf=H.finish(whole,'done')
local sf=H.finish(staged,'done')
local rf=H.finish(reversed,'done')
eq(wf:root(),sf:root(),'whole and staged cooperative discovery disagree semantically')
eq(sf:root(),rf:root(),'cooperative discovery order leaked into meaning')
print('PASS cc 11: cooperative discovery history erases to the same concurrent Development ('..count()..')')
