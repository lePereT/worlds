local H=require('speculation.relay.computation.geometry_viability.common')
 local ok,eq,count=H.counter()
local step=assert(H.Context.plug(H.authority_step_context(),{}))
local wrap=H.unary_context({definition='x'})
 local two=assert(H.Context.plug(wrap,{step}))
eq(H.A.key(step),H.A.key(two),'one-step and two-step causal chains did not share the same authority boundary profile')
local id=assert(H.Context.plug(H.authority_identity_context(),{}))
ok(H.A.key(id)~=H.A.key(step),'identity wire collapsed into causal transition profile')
print('PASS gv 01: authority profile erases causal-chain depth but preserves identity versus transition ('..count()..')')
