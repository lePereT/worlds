local H=require('speculation.showcases.transactions.transactional_recurrence_calculus.common')
local ok,eq,count=H.counter()
local recursive=H.unary_context({definition='f'})
 local base=H.authority_identity_context()
local p=H.rec_package('f',{recursive,base},{{1,2}})
 local root=p:root('f')
local d1=H.Unfold.package(p,root,1):family()
 eq(#d1.items,1)
 eq(#d1.edges,0)
local d2=H.Unfold.package(p,root,2):family()
 eq(#d2.items,2)
local frontier=H.Family.frontier(d2)
 eq(#frontier,1)
eq(#d2.items[frontier[1]].geometry.faces,1,'preferred recursive parent did not dominate after descendant completed')
ok(true)
print('PASS tr 16: recursive preference applies only to complete descendants ('..count()..')')
