local H=require('speculation.showcases.transactions.transactional_recursive_judgement.common')
 local K=H.K
 local ok,eq,count=H.counter()
local ctx=H.bool_context({1,2})
 local top=K.top(ctx)
local x=K.point_value(ctx,1,true)
 local y=K.point_value(ctx,2,true)
 local xy=K.meet(x,y)
ok(K.equal(K.meet(x,y),K.meet(y,x)),'meet not commutative')
ok(K.equal(K.meet(x,x),x),'meet not idempotent')
ok(K.equal(K.meet(top,x),x),'top not identity')
eq(K.judge(x,K.relation(ctx,function(v) return v[1] or not v[2] end)),'Hit')
eq(K.judge(x,K.point_value(ctx,1,false)),'Retry')
eq(K.judge(x,xy),'Unknown')
print('PASS rj 01: restrictive knowledge order derives Hit/Retry/Unknown ('..count()..')')
