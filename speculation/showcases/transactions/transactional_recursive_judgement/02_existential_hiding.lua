local H=require('speculation.showcases.transactions.transactional_recursive_judgement.common')
 local K=H.K
 local ok,eq,count=H.counter()
local ctx=H.bool_context({1,2,3})
 local r=K.relation(ctx,function(v) return v[1]==v[2] and v[2]==v[3] end)
local h=K.exists(r,{1,3})
 local expected=K.relation(H.bool_context({1,3}),function(v) return v[1]==v[3] end)
ok(K.equal(h,expected),'hidden witness failed to leave public correlation')
ok(not K.equal(K.top(h.ctx),h),'hiding collapsed correlation to top')
print('PASS rj 02: existential hiding preserves correlations through hidden witnesses ('..count()..')')
