local W=require('worlds')
local Construction=require('worlds.construction')
local T=require('speculation.extended_theory_lab.theory')
return function()
  local a=W.builder()
  local am=a:membrane(nil,'A')
  local ai=a:strand(am,{},'A.in')
  local ctl=a:strand(am,{},'control')
  local ao=a:strand(am,{},'A.out')
  local af=a:face(am,{ai,ctl},{ao},'A')
  local ag=a:finish()
  local b=W.builder()
  local bm=b:membrane(nil,'B')
  local bi=b:strand(bm,{},'B.in')
  local bo=b:strand(bm,{},'B.out')
  local done=b:strand(bm,{},'done')
  local bf=b:face(bm,{bi},{bo,done},'B')
  local bg=b:finish()
  local base=Construction.join({ag,bg},{})
  local g=base:result()
  local A=base:image(af)
  local B=base:image(bf)
  local th=T.state(g,{T.fact('event',A,'recursive-work'),T.fact('event',B,'recursive-work')})
  local close=Construction.join({g},{{from=base:image(ao),to=base:image(bi)},
      {from=base:image(bo),to=base:image(ai)}})
  local final=close:result()
  assert(#final:faces()==1,'mutual recursion did not become one joint Face')
  local rt=T.rebase(th,close)
  assert(rt:count('event')==1,'equivalent Face facts did not quotient with cross-component SCC')
  assert(rt:select('event')[1].args[1]==final:faces()[1],
      'Theory did not follow cross-component joint Face identity')
  return 'mutual recursion across separately built components remains ' ..
      'ordinary Worlds SCC quotient and exact Theory rebasing'
end
